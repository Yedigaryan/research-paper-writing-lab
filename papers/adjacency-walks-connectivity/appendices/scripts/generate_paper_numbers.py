#!/usr/bin/env python3
"""Generate every matrix and count printed in the paper.

Run from the paper folder:  python3 -I appendices/scripts/generate_paper_numbers.py
Writes figures/matrices.tex: macros for every matrix and for the bodies of
the tables of walk counts, sharpness, and exhaustive checks. The paper inputs
these files, so no matrix in the text is typed by hand. The exhaustive and
sharpness tables are read from the saved output of m3_connectivity.py,
which computed them; the walk counts are recomputed here by enumeration.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIG = HERE.parent.parent / "figures"
FIG.mkdir(exist_ok=True)


def mul(X, Y):
    n = len(X)
    return [[sum(X[i][r] * Y[r][j] for r in range(n)) for j in range(n)] for i in range(n)]


def power(A, k):
    P = A
    for _ in range(k - 1):
        P = mul(P, A)
    return P


def add(X, Y):
    return [[a + b for a, b in zip(r, s)] for r, s in zip(X, Y)]


def ident(n):
    return [[int(i == j) for j in range(n)] for i in range(n)]


def adj(n, edges):
    A = [[0] * n for _ in range(n)]
    for a, b in edges:
        A[a - 1][b - 1] = A[b - 1][a - 1] = 1
    return A


def tex(M):
    rows = " \\\\ ".join(" & ".join(str(x) for x in r) for r in M)
    return "\\begin{pmatrix} " + rows + " \\end{pmatrix}"


macros = {}
B = adj(3, [(1, 2), (2, 3)])          # board matrix
D = adj(3, [(1, 2)])                  # disconnected example
P4 = adj(4, [(1, 2), (2, 3), (3, 4)])  # path on four vertices


def put(name, M):
    macros[name] = tex(M)


put("MBA", B)
put("MBAtwo", power(B, 2))
put("MBAthree", power(B, 3))
put("MBAfour", power(B, 4))
put("MBAfive", power(B, 5))
put("MBS", add(B, power(B, 2)))
put("MBI", power(add(ident(3), B), 2))
put("MDA", D)
put("MDAtwo", power(D, 2))
put("MDS", add(D, power(D, 2)))
put("MDI", power(add(ident(3), D), 2))
put("MPA", P4)
put("MPAtwo", power(P4, 2))
put("MPAthree", power(P4, 3))
put("MPSshort", add(P4, power(P4, 2)))
put("MPSfull", add(add(P4, power(P4, 2)), power(P4, 3)))

# sanity checks used in the text
assert power(B, 3) == [[2 * x for x in r] for r in B]          # A^3 = 2A
assert [B[i][j] for i in range(3) for j in range(3)] == [0, 1, 0, 1, 0, 1, 0, 1, 0]
assert [power(B, 2)[i][i] for i in range(3)] == [sum(r) for r in B]  # diag of A^2 = degrees

def table_macro(name, rows):
    macros[name] = " ".join(" & ".join(str(x) for x in r) + " \\\\" for r in rows)


def write_macros():
    with open(FIG / "matrices.tex", "w") as fh:
        fh.write("% generated by appendices/scripts/generate_paper_numbers.py; do not edit\n")
        for k, v in macros.items():
            fh.write("\\newcommand{\\%s}{%s}\n" % (k, v))

# walk, trail, path, closed-walk counts on the board graph by enumeration
nbr = {1: [2], 2: [1, 3], 3: [2]}


def walks(k):
    out = [[v] for v in nbr]
    for _ in range(k):
        out = [w + [u] for w in out for u in nbr[w[-1]]]
    return out


def is_trail(w):
    es = [frozenset(p) for p in zip(w, w[1:])]
    return len(set(es)) == len(es)


rows = []
for k in range(0, 5):
    W = walks(k)
    rows.append((k, len(W), sum(is_trail(w) for w in W),
                 sum(len(set(w)) == len(w) for w in W), sum(w[0] == w[-1] for w in W)))
table_macro("TabWalkCounts", rows)
print("walk counts (k, walks, trails, paths, closed):", rows)
assert rows == [(0, 3, 3, 3, 3), (1, 4, 4, 4, 0), (2, 6, 2, 2, 4), (3, 8, 0, 0, 0), (4, 12, 0, 0, 8)]

# walks from 1 to 2 and how many are paths, k = 1..5
fromto = []
for k in range(1, 6):
    W = [w for w in walks(k) if w[0] == 1 and w[-1] == 2]
    fromto.append((k, len(W), sum(len(set(w)) == len(w) for w in W)))
print("walks 1 to 2 (k, walks, paths):", fromto)
for k, n, _ in fromto:
    assert n == power(B, k)[0][1]
table_macro("TabWalksTwelve", fromto)

# tables copied from the saved output of m3_connectivity.py
out = (HERE / "m3_connectivity.out.txt").read_text().splitlines()
sharp, exh = [], []
mode = None
for line in out:
    if line.startswith("Path graph 1-2-...-N"):
        mode = "sharp"
        continue
    if line.startswith("Exhaustive check"):
        mode = "exh"
        continue
    if mode == "sharp":
        m = re.match(r"\s+(\d+) \|\s+(\d+) \|\s+(\d+) \|\s+(\d+)\s*$", line)
        if m:
            sharp.append(m.groups())
    if mode == "exh":
        m = re.match(r"\s+(\d+) \|\s+(\d+) \|\s+(\d+) \|\s+(\d+) \|\s+(\d+) \|\s+(\d+) \|\s+(\d+) \|\s+(\d+)\s*$", line)
        if m:
            exh.append(m.groups())
assert len(sharp) == 6 and len(exh) == 5
table_macro("TabSharp", sharp)
exrows = []
for r in exh:
    n, g, c, s_, i, comp, sq, bad = r
    assert s_ == g and i == g and comp == g and sq == g
    exrows.append((n, g, c, s_, bad))
table_macro("TabExhaustive", exrows)
write_macros()
print("sharp:", sharp)
print("exhaustive:", exh)

# cost counts
for N in (10, 100, 1000):
    t = 0
    while 2 ** t < N - 1:
        t += 1
    print(f"N={N}: (N-2)N^3 = {(N-2)*N**3:,}; squarings t={t}, t*N^3 = {t*N**3:,}; N^2 = {N*N:,}")
